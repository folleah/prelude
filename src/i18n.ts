import { ref, watch } from 'vue'

const storageKey = 'prelude.language'
const savedLanguage = localStorage.getItem(storageKey)
const systemLanguage = navigator.language.toLowerCase().split('-')[0]
export const language = ref<'ru' | 'en'>(
  savedLanguage === 'ru' || savedLanguage === 'en' ? savedLanguage : systemLanguage === 'ru' ? 'ru' : 'en',
)

export function setLanguage(value: 'ru' | 'en') {
  language.value = value
  localStorage.setItem(storageKey, value)
}

watch(language, value => {
  document.documentElement.lang = value
}, { immediate: true })

