export function t(text: string, values: Record<string, string | number> = {}) {
  const translated = language.value === 'ru' ? russian[text] ?? text : text
  return translated.replace(/\{(\w+)\}/g, (placeholder, key) => String(values[key] ?? placeholder))
}
